import pandas as pd
import numpy as np

# 1. Load the file as an Excel spreadsheet since it has an OOXML structure
df = pd.read_excel('/content/14_flight_delays.csv')
print("--- 1. DATASET INSPECTION ---")
print("Shape (Rows, Columns):", df.shape)
print("\nColumns:", df.columns.tolist())
print("\nData Types:\n", df.dtypes)
print("\nFirst 5 Rows:\n", df.head())

# 2. Check for missing values and duplicate Flight_ID entries
print("\n--- 2. MISSING VALUES & DUPLICATES ---")
print("Missing values per column:\n", df.isnull().sum())
duplicates = df['Flight_ID'].duplicated().sum()
print("Duplicate Flight_ID count:", duplicates)

# Remove duplicate Flight_ID entries keeping the first occurrence
df = df.drop_duplicates(subset=['Flight_ID'], keep='first')
print("Shape after removing duplicate Flight_IDs:", df.shape)

# 3. Handle missing Arrival_Delay_Mins values and justify your method
print("\n--- 3. HANDLING MISSING ARRIVAL_DELAY_MINS ---")
# Justification: Cancelled flights naturally have NaN delays. For non-cancelled
# flights with missing values, we use the median because delay data has extreme outliers.
median_arr_delay = df['Arrival_Delay_Mins'].median()
df.loc[df['Flight_Status'] != 'Cancelled', 'Arrival_Delay_Mins'] = (
    df.loc[df['Flight_Status'] != 'Cancelled', 'Arrival_Delay_Mins'].fillna(median_arr_delay)
)
print("Filled missing Arrival_Delay_Mins (non-cancelled) with median:", median_arr_delay)
print("Remaining missing Arrival_Delay_Mins (Cancelled flights):", df['Arrival_Delay_Mins'].isnull().sum())

# 4. Convert Flight_Date to datetime and extract month and day of week
print("\n--- 4. DATE CONVERSION & FEATURE EXTRACTION ---")
df['Flight_Date'] = pd.to_datetime(df['Flight_Date'])
df['Month'] = df['Flight_Date'].dt.month_name()
df['Day_of_Week'] = df['Flight_Date'].dt.day_name()
print(df[['Flight_ID', 'Flight_Date', 'Month', 'Day_of_Week']].head())

# 5. Calculate total flights, average departure delay, and overall on-time percentage (delay <= 15 mins)
print("\n--- 5. OVERALL PERFORMANCE METRICS ---")
total_flights = len(df)
operated_flights = df[df['Flight_Status'] != 'Cancelled']
avg_dep_delay = operated_flights['Departure_Delay_Mins'].mean()
on_time_count = (operated_flights['Departure_Delay_Mins'] <= 15).sum()
on_time_pct = (on_time_count / len(operated_flights)) * 100

print(f"Total Scheduled Flights: {total_flights}")
print(f"Average Departure Delay: {avg_dep_delay:.2f} mins")
print(f"Overall On-Time Percentage (<= 15 mins): {on_time_pct:.2f}%")

# 6. Rank origin airports by average departure delay
print("\n--- 6. ORIGIN AIRPORTS RANKED BY AVG DEPARTURE DELAY ---")
airport_ranking = operated_flights.groupby('Origin')['Departure_Delay_Mins'].mean().sort_values(ascending=False)
print(airport_ranking.round(2))

# 7. Identify the 10 routes (Origin to Destination) with the highest average arrival delay
print("\n--- 7. TOP 10 ROUTES WITH HIGHEST AVG ARRIVAL DELAY ---")
df['Route'] = df['Origin'] + ' to ' + df['Destination']
operated_flights = df[df['Flight_Status'] != 'Cancelled']
top_10_routes = operated_flights.groupby('Route')['Arrival_Delay_Mins'].mean().sort_values(ascending=False).head(10)
print(top_10_routes.round(2))

# 8. Compare delay rates across times of day (Morning, Afternoon, Evening, Night)
print("\n--- 8. DELAY COMPARISON BY TIME OF DAY ---")
time_comparison = operated_flights.groupby('Time_of_Day').agg(
    Total_Flights=('Flight_ID', 'count'),
    Avg_Dep_Delay=('Departure_Delay_Mins', 'mean'),
    Avg_Arr_Delay=('Arrival_Delay_Mins', 'mean')
).round(2)
print(time_comparison)

# 9. Analyze the breakdown of delay causes (e.g., Weather, Carrier, Air Traffic)
print("\n--- 9. BREAKDOWN OF DELAY CAUSES ---")
delayed_only = df.dropna(subset=['Delay_Cause'])
cause_counts = delayed_only['Delay_Cause'].value_counts()
cause_pct = (delayed_only['Delay_Cause'].value_counts(normalize=True) * 100).round(2)
cause_summary = pd.DataFrame({'Flight_Count': cause_counts, 'Percentage (%)': cause_pct})
print(cause_summary)

# 10. Calculate cancellation and diversion percentages by airline or carrier
print("\n--- 10. CANCELLATION & DIVERSION % BY AIRLINE ---")
status_pct = pd.crosstab(df['Airline'], df['Flight_Status'], normalize='index') * 100
print(status_pct[['Cancelled', 'Diverted', 'Completed']].round(2))

# 11. Check the correlation between Departure_Delay_Mins and Arrival_Delay_Mins
print("\n--- 11. CORRELATION BETWEEN DEPARTURE & ARRIVAL DELAY ---")
correlation = operated_flights['Departure_Delay_Mins'].corr(operated_flights['Arrival_Delay_Mins'])
print(f"Correlation Coefficient: {correlation:.4f}")

# 12. Use NumPy to calculate median, standard deviation, and 90th percentile of departure delays
print("\n--- 12. NUMPY STATISTICS FOR DEPARTURE DELAYS ---")
dep_array = operated_flights['Departure_Delay_Mins'].dropna().values
median_dep = np.median(dep_array)
std_dep = np.std(dep_array)
p90_dep = np.percentile(dep_array, 90)
print(f"Median Departure Delay: {median_dep:.2f} mins")
print(f"Standard Deviation: {std_dep:.2f} mins")
print(f"90th Percentile Delay: {p90_dep:.2f} mins")

# 13. Identify extreme delay outliers using the IQR method
print("\n--- 13. EXTREME DELAY OUTLIERS (IQR METHOD) ---")
q1 = np.percentile(dep_array, 25)
q3 = np.percentile(dep_array, 75)
iqr = q3 - q1
upper_bound = q3 + 1.5 * iqr
outliers = operated_flights[operated_flights['Departure_Delay_Mins'] > upper_bound]
print(f"Q1: {q1:.2f}, Q3: {q3:.2f}, IQR: {iqr:.2f}, Upper Threshold: {upper_bound:.2f} mins")
print(f"Number of Extreme Delay Outliers: {len(outliers)}")
print(outliers[['Flight_ID', 'Airline', 'Route', 'Departure_Delay_Mins']].head())

# 14. Create a delay-severity category column using documented thresholds
print("\n--- 14. DELAY SEVERITY CATEGORIES ---")
# Documented Thresholds:
# <= 15 mins: On-Time | 16-45 mins: Minor Delay | 46-90 mins: Moderate Delay | > 90 mins: Severe Delay
conditions = [
    df['Flight_Status'] == 'Cancelled',
    df['Departure_Delay_Mins'] <= 15,
    (df['Departure_Delay_Mins'] > 15) & (df['Departure_Delay_Mins'] <= 45),
    (df['Departure_Delay_Mins'] > 45) & (df['Departure_Delay_Mins'] <= 90),
    df['Departure_Delay_Mins'] > 90
]
choices = ['Cancelled', 'On-Time', 'Minor Delay', 'Moderate Delay', 'Severe Delay']
df['Delay_Severity'] = np.select(conditions, choices, default='Unknown')
print(df['Delay_Severity'].value_counts())

# Export cleaned dataset
df.to_csv('/content/14_flight_delays_cleaned.csv', index=False)